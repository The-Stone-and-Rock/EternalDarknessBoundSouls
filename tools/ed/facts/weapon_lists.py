"""Weapons that swing from the same attack list, from the disc (InvU.bin, InvS.bin).

A held weapon's moves part is InvU +54 + place * 2 (its seven); each swing asks a move from its InvS template's
attack list (0x80150C20: entries from +0x84, 20 bytes each, +0 the move, +16 the direction). The template is InvU +136.
Writes runtime/host/weapon_lists.inc: the InvS templates whose attack list is the swords' (template 0's) and the sevens
of the weapons that use them, for wpn_part in hle.c. Run from the repo root:
    python -I tools/ed/facts/weapon_lists.py
"""
import contextlib
import io
import os
import struct
import sys

sys.path.insert(0, os.path.join('tools', 'ed', 'facts'))
sys.path.insert(0, os.path.join('tools', 'ed'))
import disc  # noqa: E402
import item_table  # noqa: E402


def attack_list(entry):
    return tuple(struct.unpack('>IIIIHH', entry[0x84 + k * 20:0x84 + k * 20 + 20]) for k in range(10))


def main():
    invs = disc.Disc().read('InvS.bin')
    lists = [attack_list(invs[o:o + s]) if s >= 0x84 + 200 else None for o, s in item_table.pack_entries(invs)]
    swords = lists[0]
    kinds = sorted(i for i, l in enumerate(lists) if l == swords)
    with contextlib.redirect_stdout(io.StringIO()):
        rows = item_table.build()['rows']
    # A row's InvS templates (item_table's inv_kinds: ed_chrs +136 of the characters that place it).
    items, sevens = set(), set()
    for r in rows:
        seven = r['record'].get('shorts54_66') or []
        found = r.get('inv_kinds') or []
        if r.get('kind') == 'WEAPONS' and seven and seven[0] > 0 and found and all(k in kinds for k in found):
            items.add(r['id'])
            sevens.add(seven[0])
    out = ['// Generated by tools/ed/facts/weapon_lists.py from InvU.bin, InvS.bin and ai/ed_chrs.dat: the weapons that',
           "// swing from the swords' attack list (InvS template 0's: the same move for each direction) and their sevens",
           '// (InvU +54), for wpn_part in hle.c. InvS templates with that list: %s.' % ', '.join(str(k) for k in kinds),
           'static const short kSwordListItems[] = {%s};' % ', '.join(str(i) for i in sorted(items)),
           'static const short kSwordListSevens[] = {%s};' % ', '.join(str(s) for s in sorted(sevens))]
    path = os.path.join('runtime', 'host', 'weapon_lists.inc')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
